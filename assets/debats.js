// « Aux comités des Communes » (14 nov. 2026) : copie de dossierquebec/commun/debats.js pour DossierCanada.
// Les réunions de comité sur un projet de loi, résumées depuis les Témoignages (scrapers/debats.js).
// être repris tel quel sur DossierCanada ou DossierBC : il lit UN fichier JSON et ne dépend de rien
// d'autre que de ses propres styles (commun/debats.css).
//
//   <div id="debats" data-src="/data/site/debats.json" data-max="4" data-lang="fr"></div>
//   <script type="module" src="/commun/debats.js"></script>
//
// Le JSON : { generatedAt, seances: [{ id, date (AAAA-MM-JJ), url (transcription officielle),
//   commissionNom, commissionNomEn, typeNom, typeNomEn, sujets[], pls[] (numéros de projets de loi),
//   legislature, session, heures: { debut, fin } | null, preliminaire, resume: { puces[], pucesEn[],
//   votes[{ objet, objetEn, pour, contre, abstentions, resultat: adopte|rejete|autre, appelNominal }],
//   aSuivre, aSuivreEn } }] }. Une séance sans `resume` n'est pas affichée.
//
// Sur une page de projet de loi (data-pl="3" data-leg="43" data-session="3"), le bloc ne garde que
// les séances de ce projet, toutes dates confondues, et s'intitule « Ses séances en commission ».

const FEUILLE = '/assets/debats.css';
const MOIS = { fr: ['janvier', 'février', 'mars', 'avril', 'mai', 'juin', 'juillet', 'août', 'septembre', 'octobre', 'novembre', 'décembre'], en: ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'] };
const JOURS = { fr: ['dimanche', 'lundi', 'mardi', 'mercredi', 'jeudi', 'vendredi', 'samedi'], en: ['Sunday', 'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday'] };
const T = {
  fr: { aujourdhui: 'Aux comités des Communes', derniere: 'Aux comités des Communes', sesSeances: 'Ses réunions en comité', seance: 'Réunion du', vote: 'Vote', votes: 'Votes', pour: 'pour', contre: 'contre', abst: 'abstention', absts: 'abstentions', nominal: 'par appel nominal', adopte: 'Adopté', rejete: 'Rejeté', autre: 'Autre', aSuivre: 'À suivre', fiche: 'Fiche du projet de loi', transcription: 'Témoignages officiels', note: 'Résumé généré par IA à partir des Témoignages publiés par la Chambre des communes, une à trois semaines après la réunion ; la transcription fait foi.', pl: 'Projet de loi', commissions: (n) => `${n} ${n > 1 ? 'commissions' : 'commission'}`, rien: 'Aucune séance de commission sur un projet de loi pour l’instant.' },
  en: { aujourdhui: 'In House of Commons committees', derniere: 'In House of Commons committees', sesSeances: 'Its committee meetings', seance: 'Meeting of', vote: 'Vote', votes: 'Votes', pour: 'for', contre: 'against', abst: 'abstention', absts: 'abstentions', nominal: 'recorded division', adopte: 'Carried', rejete: 'Defeated', autre: 'Other', aSuivre: 'Next', fiche: 'Bill page', transcription: 'Official evidence', note: 'Summary generated by AI from the Evidence published by the House of Commons one to three weeks after the meeting; the transcript is authoritative.', pl: 'Bill', commissions: (n) => `${n} ${n > 1 ? 'committees' : 'committee'}`, rien: 'No committee sitting on a bill yet.' },
};
const echapper = (s) => String(s ?? '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const dateLongue = (iso, lang) => { const [a, m, j] = iso.split('-').map(Number); const d = new Date(Date.UTC(a, m - 1, j)); return lang === 'en' ? `${JOURS.en[d.getUTCDay()]}, ${MOIS.en[m - 1]} ${j}, ${a}` : `${JOURS.fr[d.getUTCDay()]} ${j === 1 ? '1er' : j} ${MOIS.fr[m - 1]} ${a}`; };

function chargerStyle() {
  if (document.querySelector(`link[href="${FEUILLE}"]`)) return;
  const l = document.createElement('link'); l.rel = 'stylesheet'; l.href = FEUILLE; document.head.appendChild(l);
}

function carte(s, lang, t, { lienFiche = true, compact = false } = {}) {
  const en = lang === 'en';
  const r = s.resume;
  const puces = ((en && r.pucesEn?.length ? r.pucesEn : r.puces) ?? []).slice(0, compact ? 1 : 5).map((p) => (compact && p.length > 200 ? p.slice(0, 199).replace(/s+S*$/, '') + '…' : p));
  const aSuivre = en ? (r.aSuivreEn ?? r.aSuivre) : r.aSuivre;
  const titre = s.sujets?.[0] ?? '';
  // « Étude détaillée du projet de loi n° 1, Loi constitutionnelle… » → le titre de loi, après la virgule.
  const loi = (en ? s.titreLoiEn : s.titreLoi) || titre.replace(/^.*?projet de loi\s+[CS]-\d+\s*,?\s*/i, '');
  const heures = s.heures?.texte || '';
  const votes = (r.votes ?? []).map((v) => {
    const total = v.pour + v.contre + v.abstentions || 1;
    return `<div class="db-vote">
      <div class="db-vote-objet">${echapper(en ? v.objetEn || v.objet : v.objet)} <span class="db-vote-res db-vote-${v.resultat}">${t[v.resultat] ?? t.autre}</span>${v.appelNominal ? ` <span class="db-vote-nominal">${t.nominal}</span>` : ''}</div>
      <div class="db-barre" role="img" aria-label="${v.pour} ${t.pour}, ${v.contre} ${t.contre}, ${v.abstentions} ${v.abstentions > 1 ? t.absts : t.abst}"><i class="db-pour" style="width:${(v.pour / total) * 100}%"></i><i class="db-contre" style="width:${(v.contre / total) * 100}%"></i></div>
      <div class="db-legende"><b>${v.pour} ${t.pour}</b><b>${v.contre} ${t.contre}</b>${v.abstentions ? `<span>${v.abstentions} ${v.abstentions > 1 ? t.absts : t.abst}</span>` : ''}</div>
      ${v.qui ? `<div class="db-qui">${[['pour', v.qui.pour], ['contre', v.qui.contre]].map(([c, l]) => `<p><b>${t[c][0].toUpperCase() + t[c].slice(1)} :</b> ${l.map((p) => `${echapper(p.nom)}${p.parti ? ` <span class="db-parti">${echapper(p.parti)}</span>` : ''}`).join(', ')}</p>`).join('')}</div>` : ''}
    </div>`;
  }).join('');
  const pls = (s.pls ?? []).map((n) => `${t.pl} ${n}`).join(', ');
  const fiche = lienFiche && s.pls?.length ? `<a href="${en ? '/en/bills/' : '/projets-de-loi/'}${String(s.pls[0]).toLowerCase()}">${t.fiche} ${s.pls[0]} →</a>` : '';
  return `<article class="db-carte">
    <div class="db-haut"><span class="db-tag db-tag-type">${echapper(en ? s.typeNomEn : s.typeNom)}</span><span class="db-tag">${echapper(en ? s.commissionNomEn : s.commissionNom)}</span><span class="db-heure">${echapper(dateLongue(s.date, lang))}${heures ? ` · ${echapper(heures)}` : ''}</span></div>
    <h3>${echapper(pls)}${loi ? ` — ${echapper(loi)}` : ''}</h3>
    <ul>${puces.map((p) => `<li>${echapper(p)}</li>`).join('')}</ul>
    ${compact ? (r.votes?.length ? `<div class="db-votes-ligne">${en ? 'Votes' : 'Votes'} : ${[['adopte', en ? 'carried' : (r.votes.filter((v) => v.resultat === 'adopte').length > 1 ? 'adoptés' : 'adopté')], ['rejete', en ? 'defeated' : (r.votes.filter((v) => v.resultat === 'rejete').length > 1 ? 'rejetés' : 'rejeté')]].map(([k, mot]) => { const n = r.votes.filter((v) => v.resultat === k).length; return n ? `${n} ${mot}` : ''; }).filter(Boolean).join(', ')}</div>` : '') : votes ? `<div class="db-votes"><div class="db-votes-titre">${(r.votes.length > 1 ? t.votes : t.vote)}</div>${votes}</div>` : ''}
    ${aSuivre && !compact ? `<div class="db-suite"><strong>${t.aSuivre} :</strong> ${echapper(aSuivre)}</div>` : ''}
    <div class="db-liens">${fiche}<a href="${echapper(s.url)}" rel="noopener" target="_blank">${t.transcription} ↗</a></div>
  </article>`;
}

export async function rendreDebats(zone) {
  if (!zone) return;
  chargerStyle();
  const lang = zone.dataset.lang || (location.pathname === '/en' || location.pathname.startsWith('/en/') || document.documentElement.lang === 'en' ? 'en' : 'fr');
  const t = T[lang];
  const max = Number(zone.dataset.max || 4);
  const pl = zone.dataset.pl ? String(zone.dataset.pl).toUpperCase() : null;
  let donnees = null;
  try { donnees = await (await fetch(zone.dataset.src || '/data/site/debats.json', { cache: 'no-cache' })).json(); } catch (e) { zone.hidden = true; return; }
  let seances = (donnees?.seances ?? []).filter((s) => s.resume?.puces?.length);
  if (pl) seances = seances.filter((s) => s.pls?.includes(pl));
  if (!seances.length) { zone.hidden = true; return; }
  seances.sort((a, b) => b.date.localeCompare(a.date) || (a.commissionNom ?? '').localeCompare(b.commissionNom ?? ''));
  // Page Archives (data-archive="1") : toutes les réunions résumées, regroupées par jour, le plus récent ouvert.
  if (zone.dataset.archive === '1') {
    const jours = [...new Set(seances.map((s) => s.date))];
    zone.innerHTML = `<section class="db db-archives" aria-labelledby="dbArchTitre">
      <div class="db-tete"><h2 id="dbArchTitre">${lang === 'en' ? 'In House of Commons committees, day by day' : 'Aux comités des Communes, jour par jour'}</h2></div>
      ${jours.map((j, i) => { const du = seances.filter((s) => s.date === j); return `<details class="db-jour"${i === 0 ? ' open' : ''}><summary>${echapper(dateLongue(j, lang))} · ${du.length} ${lang === 'en' ? (du.length > 1 ? 'meetings' : 'meeting') : (du.length > 1 ? 'réunions' : 'réunion')}</summary>
        <div class="db-cartes">${du.map((s) => carte(s, lang, t, { lienFiche: true, compact: false })).join('')}</div></details>`; }).join('')}
      <p class="db-note">${t.note}</p>
    </section>`;
    zone.hidden = false;
    return;
  }
  const jour = seances[0].date;
  const hier = new Date(Date.now() - 864e5).toISOString().slice(0, 10);
  const auj = new Date().toISOString().slice(0, 10);
  // Sur l'accueil : le dernier jour de séance ; « Aujourd'hui » quand c'est hier ou aujourd'hui.
  const duJour = seances.slice(0, max);
  const titre = pl ? t.sesSeances : (jour >= hier ? t.aujourdhui : t.derniere);
  const sous = pl ? '' : (lang === 'en' ? `Latest meetings with published evidence, up to ${dateLongue(jour, lang)}` : `Dernières réunions dont les Témoignages sont publiés, jusqu’au ${dateLongue(jour, lang)}`);
  zone.innerHTML = `<section class="db" aria-labelledby="dbTitre">
    <div class="db-tete"><h2 id="dbTitre">${titre}</h2>${sous ? `<span>${echapper(sous)}</span>` : ''}</div>
    <div class="db-cartes">${duJour.map((s) => carte(s, lang, t, { lienFiche: !pl, compact: zone.dataset.compact === '1' })).join('')}</div>
    <p class="db-note">${t.note}${auj !== jour && !pl ? '' : ''}</p>
  </section>`;
  zone.hidden = false;
}

for (const zone of document.querySelectorAll('[data-debats], #debats')) rendreDebats(zone);
